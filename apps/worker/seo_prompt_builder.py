from typing import Any, Dict

SUPPORTED_PLATFORMS = {
    'youtube_video': 'YouTube (обычное видео)',
    'youtube_shorts': 'YouTube Shorts',
    'instagram_reels': 'Instagram Reels',
    'tiktok': 'TikTok',
}


def build_ai_video_analysis_prompt(ai_input: Dict[str, Any]) -> str:
    return (
        'Ты — AI-аналитик коротких и длинных видеороликов для соцсетей. '\
        'Проанализируй видео на основе технических данных и набора кадров. '\
        'Определи вероятный сюжет, структуру монтажа, визуальный стиль, сильные и слабые стороны ролика. '\
        'Оцени хук первых секунд, потенциальное удержание, и идеи для обложки. '\
        'Сформируй практические рекомендации по улучшению контента без обещаний гарантированного попадания в рекомендации. '\
        'Учитывай правила площадок и безопасные формулировки. '\
        f'\n\nВходные данные (JSON):\n{ai_input}'
    )


def build_platform_seo_prompt(platform: str, ai_input: Dict[str, Any]) -> str:
    platform_name = SUPPORTED_PLATFORMS.get(platform, platform)
    return (
        f'Ты — SEO-редактор для платформы {platform_name}. '\
        'На основе технического анализа и кадров подготовь SEO-пакет: заголовки, описание/caption, хештеги, теги, текст обложки, закреплённый комментарий и CTA. '\
        'Учитывай формат видео, длительность, наличие аудио, качество изображения и специфику алгоритмов платформы. '\
        'Пиши по-русски, без кликбейта и без обещаний 100% выхода в рекомендации. '\
        'Предложи улучшения, которые можно внедрить в следующей версии ролика. '\
        f'\n\nПлатформа: {platform}\nВходные данные (JSON):\n{ai_input}'
    )
